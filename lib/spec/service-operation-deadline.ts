/**
 * Срок операции (service_operations.deadline) как состояние UI: «сегодня»,
 * «просрочено N дн.», «через N дн.» — или отсутствие состояния.
 *
 * Модуль существует ради одного правила: завершённая операция не имеет
 * активного дедлайна. Раньше расчёт жил прямо в строке услуг и сравнивал
 * плановую дату с текущей всегда, поэтому исполненная операция с прошедшей
 * датой показывала «просрочено 11 дн.». Здесь сравнение с текущей датой
 * выполняется только после проверки терминального состояния, а сама плановая
 * дата не удаляется и не меняется — она остаётся историческими данными
 * (видна в модалке операции, в расходах проекта и в сводке).
 *
 * ── Почему терминальным считается completed, а не status ───────────────────
 *
 * В модели service_operations отдельной колонки status нет. Терминальное
 * состояние — отметка `completed` («Исполнено»), и она есть у всех типов
 * операций: закрыть работу можно и у монтажа, и у своей услуги. Отдельного
 * следствия у отметки нет только у доставки: при её сохранении связанные
 * материалы получают статус «Доставлено» (`delivered`), см.
 * createServiceOperation/updateServiceOperation в actions/service-operations.
 */

/**
 * Поля операции, от которых зависит срок. Структурный минимум: модуль не
 * зависит от server action и принимает и полный ServiceOperation, и урезанный
 * объект в тестах.
 */
export type DeadlineOperation = {
  /** Отметка «Исполнено» — терминальное состояние операции. */
  completed: boolean;
  /** Плановая дата, 'YYYY-MM-DD'. null — срока нет. */
  deadline: string | null;
};

/** Состояние срока: текст для строки услуги и признак «просрочено». */
export type DeadlineNote = {
  text: string;
  overdue: boolean;
};

/**
 * Срок операции или null, если показывать его как активный дедлайн нельзя:
 * дата не задана либо операция уже исполнена.
 *
 * `now` — только для тестов; без него берётся текущая дата.
 */
export function serviceOperationDeadline(
  op: DeadlineOperation,
  now: Date = new Date(),
): DeadlineNote | null {
  if (!op.deadline) return null;
  // Исполненная операция: дата — история, а не дедлайн, поэтому ни «через»,
  // ни «просрочено» не считаются и текущая дата на результат не влияет.
  if (op.completed) return null;

  return deadlineNoteFor(op.deadline, now);
}

/**
 * Строка графика платежей, от которой зависит срок.
 *
 * Структурный минимум — как у `DeadlineOperation`: модуль не зависит от server
 * action и принимает и полную строку графика, и урезанный объект в тестах.
 * `completed` здесь нет: у планового платежа нет терминального состояния — он
 * обязательство, а не работа, которую можно закрыть (закрывает его факт оплаты,
 * и это состояние считает не этот модуль).
 */
export type PaymentPlanDeadlineRow = {
  /** Плановая дата, 'YYYY-MM-DD'. null — срока нет. */
  dueDate: string | null;
};

/**
 * Срок планового платежа — ТЕМ ЖЕ правилом, что срок операции (решение O6):
 * «сегодня», «просрочено N дн.», «через N дн.» и тот же признак `overdue`.
 *
 * Отдельная функция, а не второй расчёт: два правила просрочки в одном
 * интерфейсе разошлись бы на первой же правке формулировки. Разница только в
 * терминальном состоянии — у платежа его нет, — поэтому сравнение с текущей
 * датой выполняется всегда, когда дата задана.
 */
export function paymentPlanDeadline(
  row: PaymentPlanDeadlineRow,
  now: Date = new Date(),
): DeadlineNote | null {
  if (!row.dueDate) return null;
  return deadlineNoteFor(row.dueDate, now);
}

/** Общее правило сравнения даты с текущей: текст и признак просрочки. */
function deadlineNoteFor(deadline: string, now: Date): DeadlineNote {
  const today = new Date(now);
  today.setHours(0, 0, 0, 0);
  const due = new Date(`${deadline}T00:00:00`);
  const days = Math.round((due.getTime() - today.getTime()) / 86_400_000);

  if (days === 0) return { text: "сегодня", overdue: false };
  if (days < 0) return { text: `просрочено ${-days} дн.`, overdue: true };
  return { text: `через ${days} дн.`, overdue: false };
}
