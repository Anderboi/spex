/**
 * Права на действия с фактической оплатой — в том виде, в каком их показывает
 * интерфейс.
 *
 * ── Зачем отдельный модуль ─────────────────────────────────────────────────
 *
 * Ровно та же причина, по которой существует `./service-operation-deadline`:
 * правило должно проверяться без React и без живой БД. Оно у платежей НЕ
 * выводится «на глаз» из автора: чужие записи правит ещё и администратор, а
 * наблюдатель не правит даже свои (та же граница, что у `canMutateRecord` в
 * `lib/permissions.ts` и у RLS-политик миграции).
 *
 * ── Почему это НЕ защита ───────────────────────────────────────────────────
 *
 * Здесь только UI-гейт: сервер проверяет то же самое ещё раз в
 * `actions/spec-item-payments.ts`, а приложение ходит service-role клиентом, из-за
 * чего RLS инертна (риск R3 отчёта). Скрытая кнопка не заменяет проверку на
 * сервере — она лишь не обещает пользователю действие, которое всё равно
 * откажет.
 *
 * ── Почему «своя запись» и «чужая» — разные величины ───────────────────────
 *
 * «Правлю чужую запись» — не деталь реализации, а то, что интерфейс обязан
 * сказать словами: администратор видит у чужой оплаты те же кнопки, но в
 * подтверждении отмены стоит другой текст, и человек знает, что трогает не своё.
 */

import { can, canMutateRecord, type OrgRole } from "../permissions";

/**
 * Что интерфейс знает о текущем пользователе и записи.
 *
 * `role` необязателен: вопрос «чужая ли это запись» от роли не зависит, и
 * требовать её там значило бы заставлять передавать лишнее.
 */
export type PaymentPermissionInput = {
  /** Роль пользователя в организации из сессии. `null` — вне организации. */
  role?: OrgRole | null;
  /** Идентификатор текущего пользователя. */
  userId: string | null | undefined;
  /** Автор записи; `null` — пользователь удалён (`on delete set null`). */
  createdBy: string | null | undefined;
};

/** Может ли пользователь внести оплату или возврат (решение Q3: любой, кроме viewer). */
export function canRecordPayment(input: {
  role: OrgRole | null | undefined;
}): boolean {
  return can(input.role, "record:create");
}

/** Правит ли пользователь ЧУЖУЮ запись: автор — свою, `owner`/`admin` — любую. */
export function canMutatePayment(input: PaymentPermissionInput): boolean {
  return canMutateRecord({
    role: input.role,
    userId: input.userId ?? "",
    createdBy: input.createdBy ?? null,
  });
}

/**
 * Чужая ли это запись для пользователя.
 *
 * Отдельная функция, потому что вопрос задают двое: разметка (какой текст
 * подтверждения показать) и тест. Выводить это из `authorId !== userId` в
 * разметке значило бы завести второе правило «кто автор» рядом с первым.
 *
 * Запись без автора (`createdBy === null`, пользователя удалили) чужой НЕ
 * считается: у неё нет владельца, который мог бы её защитить, и приписать её
 * текущему пользователю нельзя.
 */
export function isForeignPayment(input: PaymentPermissionInput): boolean {
  if (!input.createdBy) return false;
  return input.createdBy !== (input.userId ?? null);
}
