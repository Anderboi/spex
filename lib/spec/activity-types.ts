/**
 * Контракт ленты активности в клиентском виде.
 *
 * Отдельной модели данных здесь нет: `ActivityRecord` — это существующий
 * доменный `HistoryEntry` из `./history-types`, прочитанный `./history-read`.
 * Псевдоним заводится только ради имени в UI-слое («запись ленты») и чтобы у
 * рендерера был один импорт; дублировать поля, payload'ы или собирать данные
 * заново из `SpecItem` этот модуль не имеет права.
 *
 * ── Почему запись хранится как есть ────────────────────────────────────────
 *
 * Payload'ы исторические: их писали разные версии приложения, а `jsonb` в БД
 * не знает о наших типах. `history-mappers` уже приводит такие строки к
 * безопасному виду (отсутствующее значение — `null`, а не выдуманная
 * подстановка), и клиент обязан показывать ИМЕННО ЭТО. Выводить «что было
 * раньше» из текущего `SpecItem` нельзя: позиция с тех пор изменилась, и
 * история начала бы врать.
 *
 * ── Расширяемость ─────────────────────────────────────────────────────────
 *
 * `HistoryEntry` — размеченное объединение по `source` (`event` / `comment`),
 * а события — ещё и по `kind`. Рендерер обязан начинать с `source`/`kind` и
 * возвращать `null` на незнакомом варианте: одна непонятая запись не должна
 * ломать всю ленту.
 */

import type { ActivityRecord } from "./activity-format";
import type { HistoryCursor } from "./history-types";

/**
 * Одна запись ленты: системное событие или комментарий — как прочитано.
 *
 * Тип объявлен в `./activity-format` (там же, где форматирование) и
 * реэкспортируется здесь: у ленты должна быть одна запись этого типа, а не две
 * одинаковых в разных модулях.
 */
export type { ActivityRecord };

/** Позиция продолжения: пара `(createdAt, id)` последней выданной записи. */
export type ActivityCursor = HistoryCursor;

/**
 * Страница ленты: записи в порядке `createdAt DESC, id DESC` и курсор.
 *
 * Форма ответа сервера описана здесь, а не в `activity-format`: форматтер
 * работает с отдельной записью и о страницах ничего не знает.
 */
export type ActivityFeedPage = {
  records: ActivityRecord[];
  /** `null` — за страницей записей нет. */
  nextCursor: ActivityCursor | null;
};

/** Размер страницы первого запроса и каждой следующей порции. */
export const ACTIVITY_PAGE_SIZE = 50;

/** Сколько skeleton-записей показывать на первичной загрузке. */
export const ACTIVITY_SKELETON_COUNT = 4;
