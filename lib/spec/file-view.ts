/*  Связь с оплатой                                                    */
/* ------------------------------------------------------------------ */

/**
 * Подпись документа, прикреплённого к оплате: «К оплате от 15 октября 2026».
 *
 * Вид документа уже стоит отдельным бейджем (категория `receipt` — «Чек»),
 * поэтому здесь его нет: повторять «чек · чек» в одной строке незачем. Что
 * действительно нельзя вывести из файла — так это ДАТУ проводки, к которой он
 * прикреплён, и именно она отличает два чека одной позиции друг от друга.
 *
 * Возвращает `null` для обычного файла позиции: у него нет связи, и подписи у
 * него тоже нет. Вид записи в подпись НЕ попадает — иначе два документа к
 * возврату и к оплате читались бы одинаково («Возврат от 15 октября»), а
 * приложение уже говорит о виде пометкой в карточке факта.
 *
 * Отменённая оплата — ОСОБЫЙ случай, а не отсутствие подписи: `payment_id` в
 * строке файла остался (решение тикета: отмена документа не удаляет), и файл
 * без объяснения выглядел бы обычным документом, у которого в данных есть
 * связь в никуда. Даты у отменённой записи здесь нет: её читают вместе со
 * строкой оплаты, а строка помечена удалённой.
 */
export function paymentLinkLabel(
  payment:
    | { paidAt: string | null; cancelled?: boolean }
    | null
    | undefined,
): string | null {
  if (!payment) return null;
  if (payment.cancelled) return "К отменённой оплате";
  // `paidAt` — календарная дата `YYYY-MM-DD`, а не момент времени: `fmtDate`
  // разбирает именно такой формат без сдвига пояса.
  const date = payment.paidAt ? fmtDate(payment.paidAt) : "";
  return date ? `К оплате от ${date}` : "К оплате";
}

/**
 * Подпись документа к ЗАПЛАНИРОВАННОМУ платежу: «К запланированному платежу · до
 * 1 ноября 2026».
 *
 * ── Зачем она нужна ────────────────────────────────────────────────────────
 *
 * Счёт приходит раньше денег (ADR 0006): сначала основание, потом оплата. Пока
 * факта нет, у файла нет ни даты проводки, ни вида записи — и без подписи он
 * выглядел бы во вкладке «Файлы» обычным документом, про который непонятно,
 * почему он здесь (решение Q34). Требование «один файл, две точки входа — не
 * копия» из GLOSSARY держится именно на этом: во второй точке входа файл обязан
 * объясняться.
 *
 * Срок — единственное, что отличает один плановый платёж позиции от другого
 * (суммы повторяются, названия похожи). Поэтому он входит в подпись, а не
 * остаётся за кадром. Срока нет — подписи хватает самой: «до » без даты было бы
 * обрывком.
 *
 * ── Почему оплаченная строка сюда не доходит ───────────────────────────────
 *
 * Счёт, приложенный к плану и НЕ приложенный к оплате, после отметки обязан
 * сменить подпись на «К оплате от <дата>»: ожидание сбылось, и подписывать файл
 * по-прежнему сроком значило бы рассказывать про то, чего уже ждут напрасно.
 * Различает эти два состояния один и тот же признак — дата факта, — поэтому
 * ветка оплаты стоит ЗДЕСЬ, а не в разметке.
 */
export function plannedPaymentLinkLabel(
  plan:
    | { dueDate: string | null; paidAt?: string | null }
    | null
    | undefined,
): string | null {
  if (!plan) return null;
  if (plan.paidAt) return `К оплате от ${fmtDate(plan.paidAt)}`;
  if (!plan.dueDate) return "К запланированному платежу";
  return `К запланированному платежу · до ${fmtDate(plan.dueDate)}`;
}

/**
 * Подпись связи файла — ОДНА на два состояния документа к оплате.
 *
 * Выбор между «оплачено» и «запланировано» — правило, а не оформление, поэтому
 * живёт здесь: оплата важнее плана (она называет случившееся, а план —
 * ожидаемое), а ссылка сразу на оба состояния файла показывает факт. Ветка с
 * планом нужна для счёта, приложенного до оплаты, — после отметки «Оплачено»
 * подпись сама меняется на «К оплате от <дата>», не требуя ни правки файла, ни
 * переезда ссылки.
 */
export function filePaymentLinkLabel(file: {
  payment: { paidAt: string | null; cancelled?: boolean } | null;
  paymentPlan: { dueDate: string | null; paidAt?: string | null } | null;
}): string | null {
  return (
    paymentLinkLabel(file.payment) ?? plannedPaymentLinkLabel(file.paymentPlan)
  );
}

