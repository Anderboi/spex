/**
 * Подписи видов документа — единственный источник и для показа в списке, и для
 * выбора в диалоге загрузки.
 *
 * Порядок массива — порядок вариантов в диалоге, и он не алфавитный: сначала
 * то, что прикладывают чаще всего (документ, счёт, чек), затем бумаги, которые
 * нужны реже (договор, ТЗ, чертёж), и в конце «не назван» — текстура и «другое».
 * Первый вариант — значение по умолчанию, поэтому «Документ» стоит первым.
 *
 * Список значений обязан совпадать с `SPEC_ITEM_FILE_CATEGORIES`: подпись без
 * значения показать нечего, а значение без подписи превратилось бы в пустой
 * бейдж. Расхождение ловит тест `file-view.test.ts`.
 */
export const FILE_CATEGORY_OPTIONS: readonly {
  value: SpecItemFileCategory;
  label: string;
}[] = [
  { value: "document", label: "Документ" },
  { value: "invoice", label: "Счёт" },
  { value: "receipt", label: "Чек" },
  { value: "contract", label: "Договор" },
  { value: "specification", label: "ТЗ / спецификация" },
  { value: "drawing", label: "Чертёж / схема" },
  { value: "texture", label: "Текстура" },
  { value: "other", label: "Другое" },
];

/**
 * Подпись категории файла.
 *
 * Берётся именно сохранённое `category`, а не выводится заново из MIME: тип
 * содержимого и то, чем файл считает пользователь, — разные вещи, и повторное
 * определение переписало бы его выбор.
 *
 * Запасное «Другое» — от значения, которого нет в списке (так выглядела бы
 * строка, записанная в БД в обход кода). Категорию это не подменяет — просто не
 * даёт показать пустой бейдж.
 */
export function fileCategoryLabel(category: SpecItemFileCategory): string {
  return (
    FILE_CATEGORY_OPTIONS.find((option) => option.value === category)?.label ??
    "Другое"
  );
}

/* ------------------------------------------------------------------ */
/*  Строка списка                                                      */
/* ------------------------------------------------------------------ */

/**
 * Дата загрузки тем же форматтером, что и остальные даты проекта
 * (`fmtDate` → «6 октября 2026»). Своего форматтера не заводим: мусорная дата
 * из API даёт пустую строку, а не «Invalid Date».
 */
export function formatFileDate(createdAt: string): string {
  const date = new Date(createdAt);
  if (Number.isNaN(date.getTime())) return "";
  return fmtDate(createdAt);
}

/**
 * Те же метаданные строки одной подписью: «1.2 MB · Андрей · 6 октября 2026».
 *
 * Нужна там, где части показываются ОДНИМ текстом, а не отдельными элементами:
 * правило «что попадает в подпись и в каком порядке» живёт в `fileMetaParts`, и
 * склейка здесь — только разделитель. Пустые части опускаются: мусорная дата не
 * оставляет висящий разделитель.
 */
export function fileMetaLine(args: {
  sizeBytes: number;
  /**
   * Дата загрузки. Пустая строка означает «не показывать дату».
   */
  createdAt: string;
  author?: string | null;
}): string {
  return fileMetaParts(args).join(" · ");
}

/**
 * Те же метаданные строки, но по частям: размер, автор, дата.
 *
 * Нужны там, где части показываются РАЗНЫМИ элементами (строка списка: чип вида,
 * размер, дата, автор — отдельными узлами). Склейка `fileMetaLine` — для мест,
 * где метаданные это одна строка; правило «что попадает в подпись и в каком
 * порядке» живёт здесь одно, поэтому две формы подписи не разъедутся.
 *
 * Пустые части опускаются: мусорная дата не оставляет висящий разделитель.
 */
export function fileMetaParts(args: {
  sizeBytes: number;
  createdAt: string;
  author?: string | null;
}): string[] {
  const parts = [formatFileSize(args.sizeBytes)];
  if (args.author) parts.push(args.author);
  const date = formatFileDate(args.createdAt);
  if (date) parts.push(date);
  return parts;
}

