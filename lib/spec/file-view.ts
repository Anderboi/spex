/**
 * Отображение файла позиции: формат размера, вид файла и подпись автора.
 *
 * Чистые функции без React, БД и Next — ровно то, что можно проверить
 * unit-тестами. Компонент (`FilesTab`) их только вызывает, поэтому правило
 * существует в одном месте: «какая иконка у PDF» и «как показать 1.2 МБ»
 * не размазаны по разметке.
 *
 * Серверная модель здесь НЕ дублируется: тип входа (`SpecItemFileEntry`)
 * импортируется из ядра файлов, второго описания тех же полей нет.
 */

import { fmtDate, humanSize } from "@/lib/utils";
import {
  isSpecItemFileCategory,
  type SpecItemFileCategory,
} from "@/lib/spec/file-content";
import type { SpecItemFileEntry } from "@/lib/spec/spec-item-files";

/* ------------------------------------------------------------------ */
/*  Размер                                                             */
/* ------------------------------------------------------------------ */

/**
 * Человекочитаемый размер файла.
 *
 * Тонкая обёртка над общим `humanSize` (`lib/utils.ts`), а не второй
 * форматтер: разделение B / KB / MB и округление живут там, здесь — только
 * имя для домена файлов. Так у проекта остаётся ОДНО правило форматирования
 * размера.
 */
export function formatFileSize(bytes: number): string {
  return humanSize(bytes);
}

/* ------------------------------------------------------------------ */
/*  Вид файла                                                          */
/* ------------------------------------------------------------------ */

/**
 * Вид файла по формату и его классификация живут в ядре
 * (`./file-content`, `fileKindOf`): по этому же правилу сервер угадывает вид
 * документа при загрузке, и вторая копия здесь разошлась бы с ним молча.
 * Реэкспорт — только для удобства потребителей вида (иконка в списке).
 */
export { fileKindOf, type SpecItemFileKind } from "./file-content";

/** Расширение из имени файла: только буквы и цифры, не длиннее 5. */
export function fileExtension(fileName: string): string {
  const match = /\.([a-z0-9]{1,5})$/i.exec((fileName ?? "").trim());
  return match ? match[1].toLowerCase() : "";
}

/* ------------------------------------------------------------------ */
/*  Автор                                                              */
/* ------------------------------------------------------------------ */

/**
 * Подпись автора файла: имя, под которым файл загрузили.
 *
 * Имя приходит в записи (`uploadedByName`), а не выводится здесь: uuid в
 * подпись не годится (это внутренний идентификатор), а имя живёт в таблице
 * `users` и читается запросом — там же, где читаются подписи оплат.
 *
 * Пустое имя читается как «автора нет»: пользователя могли удалить
 * (`on delete set null`), тогда `uploadedBy` тоже `null`. Строка просто не
 * показывает автора, а не подставляет прочерк.
 */
export function fileAuthorLabel(file: SpecItemFileEntry): string | null {
  const name = file.uploadedByName?.trim();
  return name && name.length > 0 ? name : null;
}

/* ------------------------------------------------------------------ */
/*  Область приёма файлов                                              */
/* ------------------------------------------------------------------ */

/**
 * Ушёл ли курсор перетаскивания ИЗ зоны (а не на её дочерний элемент).
 *
 * Стандартная ловушка drag-событий: `dragleave` приходит и при переходе на
 * вложенный элемент, поэтому «снимать подсветку по любому `dragleave`» даёт
 * мигание на каждой строке списка. Правило — «вышли, если `relatedTarget` вне
 * зоны» — вынесено сюда отдельной функцией, потому что проверить его через
 * синтетические события библиотеки тестирования нельзя: `relatedTarget` у них
 * не проставляется. Здесь же оно проверяется на настоящих узлах DOM.
 *
 * Возвращает `true`, только если уход подтверждён: если `relatedTarget` нет
 * (браузер его не сообщил), считаем, что курсор ушёл — иначе подсветка могла бы
 * остаться навсегда.
 */
export function isLeavingDropZone(
  zone: Pick<Node, "contains"> | null,
  relatedTarget: EventTarget | null,
): boolean {
  if (!zone) return true;
  const next = relatedTarget as Node | null;
  if (!next) return true;
  return !zone.contains(next);
}

