/**
 * Токены запросов мутаций комментария: какие ответы ещё актуальны.
 *
 * ── Зачем отдельный модуль ────────────────────────────────────────────────
 *
 * React-тестов в проекте нет, поэтому «какой ответ устарел» вынесено в чистые
 * функции и проверяется обычным Vitest в сценариях с разными порядками ответов.
 * Хук (`useCommentMutations`) остаётся обвязкой: взять токен, вызвать action,
 * применить ответ только если он актуален.
 *
 * ── Почему токен на каждый `commentId`, а не один на хук ──────────────────
 *
 * Один общий счётчик делал операции независимых комментариев взаимно
 * устаревающими: правка A и удаление B получали номера 1 и 2, и ответ A
 * сравнивался с номером B. Последствия хуже, чем «ответ проигнорирован»:
 * вышедшая раньше функция не снимала `pending`, и операция A оставалась
 * навсегда «в полёте» — с заблокированными кнопками и без права на повтор.
 *
 * Операции над разными комментариями независимы по построению (состояние
 * хранится как `Map<commentId, …>`), поэтому и токен обязан быть на
 * `commentId`. Инвалидирует операцию только НОВАЯ операция того же
 * комментария — это и есть правило «одна активная операция на комментарий».
 *
 * Ответ считается актуальным, только если его токен — текущий токен своего
 * `commentId`. Проверка идёт ровно один раз, перед применением результата:
 * после неё ответ либо применяется целиком, либо не трогает ничего — включая
 * `pending`, результат и ошибку.
 */

type CommentRequestCounter = {
  /** Следующий номер для этого комментария. */
  next: number;
  /** Номер последнего запущенного запроса — он и считается актуальным. */
  issued: number;
};

/** Токен конкретного запроса: `commentId` плюс его номер. */
export type CommentRequestToken = {
  commentId: string;
  requestId: number;
};

export type CommentRequestTokens = ReadonlyMap<string, CommentRequestCounter>;

/**
 * Начать новый запрос по комментарию.
 *
 * Возвращается токен запуска и обновлённая карта: предыдущий запрос того же
 * комментария после этого устаревает сам собой, потому что его номер перестаёт
 * быть текущим.
 */
export function beginCommentRequest(
  tokens: CommentRequestTokens,
  commentId: string,
): { token: CommentRequestToken; tokens: CommentRequestTokens } {
  const current = tokens.get(commentId);
  const requestId = (current?.next ?? 1);

  const next = new Map(tokens);
  next.set(commentId, { next: requestId + 1, issued: requestId });

  return { token: { commentId, requestId }, tokens: next };
}

/**
 * Актуален ли ответ этого запроса.
 *
 * `false` — ответ устарел: за время запроса запустили более новый по тому же
 * комментарию. Такой ответ обязан быть проигнорирован ПОЛНОСТЬЮ: он не снимает
 * `pending` новой операции, не подменяет её результат и не показывает свою
 * ошибку.
 *
 * Комментария нет в карте — по нему ничего не запускали (или карта сброшена):
 * применять ответ некуда, поэтому тоже `false`.
 */
export function isCommentRequestCurrent(
  tokens: CommentRequestTokens,
  token: CommentRequestToken,
): boolean {
  return tokens.get(token.commentId)?.issued === token.requestId;
}
