/**
 * Сегодняшний день для полей даты платежа.
 *
 * ── Почему не `toISOString()` ──────────────────────────────────────────────
 *
 * `toISOString()` отдаёт UTC. Для Москвы вечером 1 ноября он вернул бы
 * 31 октября, то есть платежи «уезжали» бы на день назад относительно календаря
 * пользователя, а `<input type="date">` показывал бы не тот день, который
 * записался. Явная сборка из ЛОКАЛЬНЫХ частей совпадает и с полем формы, и с
 * `current_date` в БД для того же часового пояса.
 *
 * ── Почему отдельный модуль ────────────────────────────────────────────────
 *
 * Функция нужна в двух местах: ядру (`./payment-mutations` — подставить день,
 * если пользователь его не задал) и вкладке (`payments-tab` — показать день в
 * форме). Вторая копия разошлась бы с первой на первой правке, а импортировать
 * ядро в клиентский компонент нельзя: оно тянет типы Supabase.
 */

/** Сегодняшний день 'YYYY-MM-DD' по локальному календарю. */
export function todayIso(now: Date = new Date()): string {
  const year = String(now.getFullYear()).padStart(4, "0");
  const month = String(now.getMonth() + 1).padStart(2, "0");
  const day = String(now.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}
