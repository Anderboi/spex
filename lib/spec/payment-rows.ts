/**
 * Строки вкладки «Платежи»: план и факт — ОДНА строка на экране.
 *
 * ── Откуда взялось правило ─────────────────────────────────────────────────
 *
 * План и факт — две разные строки ХРАНИЛИЩА (`spec_item_payment_plans` и
 * `spec_item_payments`), и это не пересматривается: остаток и процент считаются
 * только по фактам (ADR `docs/adr/0003-ostatok-ot-stoimosti.md`), а плановая
 * таблица знает виды платежа иначе, чем факт. Но на экране пользователь ведёт
 * ОДНО обязательство: он поставил счёт, назвал срок, а потом отметил
 * «Оплачено» — и ждёт, что строка не удвоится, а сменит состояние
 * (ADR `docs/adr/0006-grafik-platezhey-vozvrashchaetsya.md`).
 *
 * Отсюда этот модуль: он и только он решает, что попадает в список и в каком
 * порядке. Вкладка о правиле не знает — она рисует готовые строки.
 *
 * ── Почему чистая функция, а не разметка ───────────────────────────────────
 *
 * Соединение ломается НЕЗАМЕТНО: лишняя строка не роняет вкладку, она просто
 * показывает один и тот же платёж дважды, и остаток в шапке перестаёт сходиться
 * с тем, что видно в списке. Проверять такое правило разметкой — значит
 * проверять его один раз и случайно; здесь оно проверяется тестом без React.
 *
 * ── Три состояния строки и почему их именно три ────────────────────────────
 *
 *   * **неоплаченная строка графика** — план есть, живого факта по нему нет:
 *     маркер «Запланирован». Сюда же попадает строка, оплата по которой
 *     ОТМЕНЕНА: обязательство снова открыто, но `cancelledPayment` несёт след
 *     отмены (решение Q29) — молча вернуть строку в неоплаченное значило бы
 *     стереть факт, который пользователь помнит;
 *   * **оплаченная строка графика** — факт встаёт в строку плана;
 *   * **факт вне графика** — план не назван (или названная строка удалена):
 *     оплата вне графика и возврат. Отдельного состояния «план удалён» здесь
 *     нет: строка обязательства исчезла, а деньги остались — и прятать их
 *     нельзя, иначе остаток в шапке посчитает то, чего не видно в списке.
 *
 * ── Почему порядок планов задаёт сервер, а фактов — он же ──────────────────
 *
 * Строки графика приходят по `position`, факты — по `paid_at desc,
 * created_at desc`; вкладка не пересортировывает ни то, ни другое. Единственное,
 * что решается здесь, — ЧТО идёт раньше: строки графика, затем факты вне его.
 * Так список читается сверху вниз как график, а «оплачено вне графика» стоит
 * после него, а не вклинивается между обязательствами.
 */

import type { PaymentPlanEntry } from "./payment-plan-types";
import type { PaymentEntry } from "./payment-types";

/**
 * Строка вкладки: план, факт или оба сразу.
 *
 * `key` — не идентификатор записи, а идентификатор СТРОКИ: у неоплаченного
 * плана идентификатора факта ещё нет, а у оплаченного их два. Собирается из
 * того, что строку и составляет, поэтому не меняется при обновлении полей и
 * годится ключом React.
 */
export type PaymentRowEntry = {
  key: string;
  /** Строка графика. `null` — факт вне графика. */
  plan: PaymentPlanEntry | null;
  /** Живой факт по этой строке. `null` — ещё не оплачено. */
  payment: PaymentEntry | null;
  /**
   * Отменённая оплата этой строки — пометка, а не состояние.
   *
   * Есть только там, где строка вернулась в «Не оплачено» после отмены: пока
   * живого факта нет, пользователь обязан видеть, что оплата была. У строки с
   * новым фактом пометки нет — отменённое осталось в журнале, а строка закрыта.
   */
  cancelledPayment?: PaymentEntry;
};

/**
 * Строки вкладки из того, что прочитано сервером.
 *
 * `cancelledPayments` — мягко удалённые факты, привязанные к строкам графика.
 * Они не попадают в список как самостоятельные строки: их место занимает
 * пометка у той строки, которую они когда-то закрыли.
 */
export function buildPaymentRows(args: {
  /** Активные строки графика в серверном порядке (`position`, затем `id`). */
  plans: readonly PaymentPlanEntry[];
  /** Живые факты в серверном порядке (`paid_at desc`, затем `created_at desc`). */
  payments: readonly PaymentEntry[];
  /** Отменённые факты в серверном порядке — по ним строка получает пометку. */
  cancelledPayments?: readonly PaymentEntry[];
}): PaymentRowEntry[] {
  const plans = [...args.plans].sort((a, b) =>
    a.position === b.position
      ? a.id < b.id
        ? -1
        : a.id > b.id
          ? 1
          : 0
      : a.position - b.position,
  );

  /** Кто занял строку плана: `planId` → факт. */
  const takenBy = new Map<string, PaymentEntry>();
  /** Факты, которым строки плана не нашлось: они станут своими строками. */
  const loose: PaymentEntry[] = [];

  for (const payment of args.payments) {
    const planId = payment.paymentPlanId;
    if (planId === null || takenBy.has(planId)) {
      // Второй факт по одной строке интерфейсом не создаётся (отметка
      // «Оплачено» ставится у неоплаченной строки), но данные этого не
      // запрещают. Лишний факт терять нельзя: он уходит своей строкой.
      loose.push(payment);
      continue;
    }
    takenBy.set(planId, payment);
  }

  const planIds = new Set(plans.map((plan) => plan.id));

  // Факт, чья строка графика удалена, своей строкой тоже показывается: деньги
  // остались, а обязательства, к которому они относятся, в списке уже нет.
  for (const [planId, payment] of takenBy) {
    if (!planIds.has(planId)) {
      loose.push(payment);
      takenBy.delete(planId);
    }
  }

  /** Последняя отменённая оплата каждой строки: серверный порядок — поздние первыми. */
  const cancelledByPlan = new Map<string, PaymentEntry>();
  for (const payment of args.cancelledPayments ?? []) {
    const planId = payment.paymentPlanId;
    if (planId === null || cancelledByPlan.has(planId)) continue;
    cancelledByPlan.set(planId, payment);
  }

  const rows: PaymentRowEntry[] = plans.map((plan) => {
    const payment = takenBy.get(plan.id) ?? null;
    const cancelled = payment === null ? cancelledByPlan.get(plan.id) : undefined;

    return {
      key: `${plan.id}:plan`,
      plan,
      payment,
      ...(cancelled ? { cancelledPayment: cancelled } : {}),
    };
  });

  for (const payment of loose) {
    rows.push({ key: `${payment.id}:payment`, plan: null, payment });
  }

  return rows;
}
