/**
 * Данные формы платежей: то, что форма отдаёт вкладке.
 *
 * ── Почему отдельный модуль ────────────────────────────────────────────────
 *
 * Значения этих двух видов нужны ДВУМ компонентам: форма вкладки «Платежи»
 * (`payment-form` — план, факт и возврат одной формой) и карточка строки графика
 * (`payment-plan-form`), оставшаяся от прежнего показа. Живи
 * `PaymentPlanFormValues` внутри `payment-form`, вторая форма импортировала бы
 * тип из первой — связь «форма знает о форме» вместо «обе знают о контракте
 * вкладки».
 *
 * Модуль без зависимостей: ни React, ни клиента БД. Импортировать его может и
 * клиентский компонент, и тест — в бандл ничего лишнего не тянется.
 */

import type { PaymentRecordKind } from "./payment-types";
import type { SpecItemFileCategory } from "./file-content";

/**
 * Прикрепляемый документ: файл плюс названная человеком роль.
 *
 * Роль — вид документа: у документа к оплате его несёт вид (`invoice` —
 * основание, `receipt` — подтверждение), а формат роль не различает (ADR 0005).
 * Поэтому пара «файл + вид» и есть то, что форма передаёт родителю: отправляет
 * файлы он, после того как запись сохранена и её идентификатор известен.
 */
export type PaymentFormUpload = {
  file: File;
  category: SpecItemFileCategory;
};

/**
 * Значения ФАКТА в том виде, в каком их принимает действие.
 *
 * `paidAt` — `null` означает «сегодня»: `<input type="date">` отдаёт пустую
 * строку, а подставлять дату за пользователя форма не имеет права.
 */
export type PaymentFormValues = {
  kind: PaymentRecordKind;
  amount: number;
  paidAt: string | null;
  paymentPlanId: string | null;
  comment: string | null;
};

/**
 * Значения строки ГРАФИКА: создание и правка одной разметкой.
 *
 * `position` здесь нет: строку ставят в конец графика, и перестановка — отдельное
 * действие со своим событием (`movePaymentPlan`).
 */
export type PaymentPlanFormValues = {
  title: string;
  amount: number;
  condition: string | null;
  dueDate: string | null;
};
