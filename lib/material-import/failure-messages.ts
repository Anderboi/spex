/**
 * Причины, для которых полезно уточнить статус ответа: без него «страница
 * недоступна» не отличить от «нет такой страницы».
 */
const STATUS_HINTS: Record<number, string> = {
  401: "Страница требует авторизации на сайте",
  403: "Сайт запретил автоматический доступ к странице",
  404: "Страницы по этой ссылке нет — возможно, товар снят с продажи",
  410: "Товар удалён с сайта",
  429: "Сайт ограничил частоту запросов. Попробуйте позже",
  500: "На сайте ошибка. Попробуйте позже",
  502: "Сайт временно недоступен. Попробуйте позже",
  503: "Сайт временно недоступен. Попробуйте позже",
  504: "Сайт не ответил вовремя. Попробуйте позже",
};

/** Текст и подсказка для кода отказа. Неизвестный код не должен ломать UI. */
export function describeImportFailure(
  code: FetchFailureCode,
  status?: number,
): ImportFailureMessage {
  const base = MESSAGES[code] ?? {
    message: "Не удалось импортировать материал",
    hint: "Попробуйте другую ссылку или добавьте материал вручную",
  };

  if (code === "HTTP_ERROR" && status && STATUS_HINTS[status]) {
    return { message: base.message, hint: STATUS_HINTS[status] };
  }

  return base;
}
