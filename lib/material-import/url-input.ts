/**
 * Клиентская проверка ссылки для импорта материала.
 *
 * Нужна ровно для одного: не отправлять заведомо пустой ввод и дать быструю
 * подсказку, пока кнопка ещё не нажата. НАСТОЯЩАЯ проверка адреса — схема, порт,
 * отсутствие учётных данных, приватные диапазоны, DNS и каждый редирект —
 * выполняется на сервере (`guards.ts` / `fetch.ts`). Повторять её здесь нельзя:
 * появилась бы вторая, расходящаяся реализация политики безопасности.
 *
 * Модуль обязан оставаться клиентским: `guards.ts` тянет `node:dns`, и импорт
 * оттуда в компонент утащил бы серверный код в браузерный бандл.
 */

/**
 * Похоже ли значение на адрес страницы, который вообще имеет смысл отправлять.
 *
 * `http:` пропускаем: страницу по нему сервер разберёт и ответит человеческой
 * причиной отказа (`UNSUPPORTED_PROTOCOL`), а блокировать кнопку на этом уровне
 * значило бы дублировать серверную политику.
 */
export function isProbablyImportUrl(value: string): boolean {
  const trimmed = value.trim();
  if (!trimmed) return false;
  try {
    const url = new URL(trimmed);
    return url.protocol === "http:" || url.protocol === "https:";
  } catch {
    return false;
  }
}
