/**
 * Машиночитаемая причина отказа. Клиенту иногда мало текста: одно и то же
 * «не получилось» требует разного поведения в UI (например, «материал уже
 * в проекте» — это не ошибка ввода, а состояние, которое надо показать в
 * списке, а не только тостом). Текст остаётся для человека, код — для логики.
 */
export type ActionErrorCode =
  | "ALREADY_IN_PROJECT"
  | "FORBIDDEN"
  | "NOT_FOUND"
  | "INVALID_INPUT"
  /**
   * Импорт по URL не удался: страница недоступна, отдала не HTML или не
   * поместилась в лимиты. Отдельный код нужен, потому что это не ошибка ввода
   * и не отказ прав — UI показывает её иначе, с предложением проверить ссылку.
   */
  | "IMPORT_FAILED"
  /**
   * Родитель комментария не годится для ответа: его нет, он из другой позиции
   * или мягко удалён. Отдельный код нужен потому, что это не ошибка формата
   * ввода (текст корректен) и не «не найдено» для всей операции: UI показывает
   * разное — «комментарий недоступен» против «позиция не найдена».
   */
  | "INVALID_PARENT"
  /**
   * Операция не удалась по причине, которую пользователь не может исправить:
   * отказ БД, недоступный сервис. Отличается от `INVALID_INPUT` тем, что
   * подсвечивать поле ввода бессмысленно — текст был корректен.
   */
  | "FAILED";

export type ActionResult<T = null> =
  | { success: true; data: T }
  | { success: false; error: string; code?: ActionErrorCode };

export function ok<T>(data: T): ActionResult<T> {
  return { success: true, data };
}
export function fail<T = never>(
  error: string,
  code?: ActionErrorCode,
): ActionResult<T> {
  return code ? { success: false, error, code } : { success: false, error };
}
