import { screen, within } from "@testing-library/react";

/**
 * Поиск чипса документа — ОДНО правило на два тестовых файла.
 *
 * Чипс показывает вид документа, а имя файла уносит в доступное имя: два чека на
 * разные суммы различаются только им. Поэтому и в тестах чипс находится ПО ИМЕНИ
 * ФАЙЛА, а не по тексту, — и правило поиска обязано совпадать с тем, что видит
 * диктор.
 *
 * ── Почему `getByRole("img")`, а не `getByLabelText` ───────────────────────
 *
 * `aria-label` в чипсе работает только потому, что у элемента есть роль, на
 * которой имя разрешено (см. докблок `FileChip`). `getByLabelText` этого не
 * проверяет: он найдёт ярлык и на роли, которая его игнорирует, — то есть тест
 * подтвердил бы доступность, которой нет. `getByRole` считает имя так же, как его
 * считает диктор, и служит проверкой самого решения о роли.
 *
 * Файл намеренно вне шаблона тестов (`*.test.tsx`) и без своих `describe`: это
 * помощник, а не набор тестов. Второй копии этих двух функций в двух тестовых
 * файлах быть не должно — они уже разъехались бы в первой же правке формата имени.
 */
export function documentChip(fileName: string): HTMLElement {
  return screen.getByRole("img", { name: documentChipName(fileName) });
}

/** То же, но внутри карточки: чипс ищется у СВОЕЙ оплаты. */
export function documentChipIn(card: HTMLElement, fileName: string): HTMLElement {
  return within(card).getByRole("img", { name: documentChipName(fileName) });
}

/**
 * Регулярное выражение доступного имени чипса.
 *
 * Подпись вида неизвестна заранее («Чек», «Счёт», «Документ»), поэтому её место
 * занимает `[^:]+`, а имя файла экранируется: точки в «Чек №7.pdf» — это точка в
 * регулярном выражении, а не любая буква.
 */
function documentChipName(fileName: string): RegExp {
  return new RegExp(`^[^:]+: ${escapeRegExp(fileName)}$`);
}

/** Экранирование имени файла для регулярного выражения доступного имени. */
function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
