import type { SpecDensity } from "@/hooks/use-spec-density";

/**
 * Раскладка списка позиций проекта.
 *  - `table`   — таблица: единственный вид, где одновременно видны код,
 *                количество, цена и статус;
 *  - `list`    — плотная строка `SpecListRow` (обзор, правка — в детализации);
 *  - `compact` — компактная карточка `SpecCompactCard`;
 *  - `card`    — полная карточка `SpecCard`.
 */
export type SpecListLayout = "table" | "list" | "compact" | "card";

/**
 * Пороги — в пикселях контейнера, а не окна (см. `useContainerWidth`).
 *
 * `896` (= 56rem, `min-w` самой таблицы) — минимум для таблицы: ровно с этой
 * ширины она помещается без горизонтальной прокрутки, поэтому замер округляется
 * вниз. Фиксированные колонки при скрытых превью и «услугах» занимают 624px
 * (чекбокс 24, марка 56, кол-во 136, цена 112, итого 112, статус 136, действия
 * 48), поэтому наименованию остаётся ≥ 272px. Дальше второстепенные колонки
 * возвращаются по приоритету: «услуги» (рабочие данные) — с 928px, превью — с
 * 1024px. Минимальная ширина наименования по всем полосам — 208px.
 *
 * `640` — ниже этого строка-обзор перестаёт помещаться: марка, наименование и
 * сумма конкурируют за место, поэтому отдаём выбор карточкам и их плотности.
 */
export const SPEC_TABLE_MIN_CONTAINER = 896;
export const SPEC_LIST_MIN_CONTAINER = 640;

export function resolveSpecListLayout(
  containerWidth: number,
  density: SpecDensity,
): SpecListLayout {
  if (containerWidth >= SPEC_TABLE_MIN_CONTAINER) return "table";
  if (containerWidth >= SPEC_LIST_MIN_CONTAINER) return "list";
  // `row` — та же плотная строка, что и `list`: раскладки совпадают.
  return density === "row" ? "list" : density;
}

/**
 * Классы колонок таблицы позиций. Одни и те же значения обязаны стоять на `th`
 * (`group-section.tsx`) и на `td` (`spec-row.tsx`): разойдутся — шапка съедет
 * относительно тела. Container queries здесь вместо media queries, потому что
 * ширина контейнера меняется ещё и от сворачивания сайдбара.
 *
 * `min-w-[56rem]` (= 896px, `SPEC_TABLE_MIN_CONTAINER`) — «пол» для
 * наименования: в fixed-раскладке `min-width` на ячейке игнорируется по
 * спецификации CSS, поэтому единственный способ не дать колонке схлопнуться в
 * ноль — задать минимальную ширину самой таблице. Держать эти два значения
 * синхронными обязательно: иначе либо появится постоянный горизонтальный
 * скролл, либо таблица будет включаться раньше, чем влезает.
 */
export const SPEC_TABLE_CLASS = "w-full min-w-[56rem] table-fixed";

/** «Услуги» — рабочие данные (доставка, монтаж, доп. расходы по позиции),
 *  поэтому возвращаются первыми: с 58rem (928px). */
export const SPEC_COL_SERVICES = "hidden @[58rem]:table-cell";

/** Превью уходит первым: материал опознают по названию, бренду и артикулу, а
 *  «услуги» — рабочие данные. Возвращается с 64rem (1024px); до этого
 *  наименованию остаётся 208–304px. */
export const SPEC_COL_IMAGE = "hidden @[64rem]:table-cell";

/**
 * Обёртка таблицы: `@container` — точка отсчёта для container queries колонок,
 * `overflow-x-auto` — страховка на случай, когда таблица всё же шире контейнера
 * (зум, крупный минимальный шрифт браузера, будущие колонки). Область
 * фокусируемая, иначе с клавиатуры до правых колонок не добраться.
 */
export const SPEC_TABLE_SCROLL =
  "@container overflow-x-auto focus-visible:outline-2 focus-visible:-outline-offset-2 focus-visible:outline-fg-brand";
