-- ============================================================================
-- Основание у планового платежа: public.spec_item_files.payment_plan_id
-- ============================================================================
--
-- Тикет `.scratch/material-payments/issues/08-grafik-platezhey-s-otmetkoy-oplacheno.md`,
-- ADR docs/adr/0006-grafik-platezhey-vozvrashchaetsya.md.
--
-- Показ графика возвращается, и вместе с ним возвращается вопрос, который был
-- причиной его отказа 2026-10-10: строка плана копировала факт и «не сообщала
-- ничего сверх фактов». Теперь ей есть что сообщать — счёт, приложенный ДО
-- оплаты. Порядок стал обратным тому, что отвергли: сначала приходит документ,
-- деньги потом.
--
-- ── Почему одна колонка, а не новая таблица ─────────────────────────────────
--
-- Документ к оплате — ОБЫЧНЫЙ файл позиции (ADR 0005, GLOSSARY «Документ к
-- оплате»): у него уже есть метаданные, вид, приватный bucket, права и мягкое
-- удаление. Добавляется ровно вторая ссылка — на строку плана, — и эта ссылка
-- НЕ заменяет первую: счёт остаётся привязан к плану и после отметки «Оплачено»
-- получает связь с фактом. Переезд ссылки был бы переписыванием финансовой
-- истории (ADR 0004) плюс окно между созданием оплаты и переездом, в котором
-- оплата осталась бы без документа.
--
-- ── Запрет каскадного удаления ──────────────────────────────────────────────
--
-- `on delete restrict`, как у всей финансовой истории (ADR 0004) и как у
-- `payment_id` в `20261011_001`. Практический эффект тот же: физически удалить
-- строку графика, к которой прикреплён документ, нельзя, а мягкое удаление
-- (`deleted_at`) ссылку не трогает — документ остаётся в истории позиции и в
-- вкладке «Файлы».
--
-- ── Поведение триггера: NULL, а не ошибка ───────────────────────────────────
--
-- Зеркало `spec_item_files_payment_scope` из `20261011_001`, и по той же
-- причине. Расхождение позиции, организации или проекта означает ИСПОРЧЕННУЮ
-- ссылку, а не «поле надо подтянуть»: триггер обнуляет `payment_plan_id` (в лог
-- уходит `raise notice`), и строка файла остаётся работоспособной — документ
-- открывается и удаляется как обычный файл позиции.
--
-- Почему не `raise exception`: ссылка ведёт в ДРУГУЮ таблицу, и её актуальность
-- может измениться без участия файла (строку графика удалили мягко, позицию
-- перенесли в другой проект). Ошибка запретила бы тогда любое обновление строки
-- файла — в том числе мягкое удаление испорченного документа. Пользователю
-- чужой `payment_plan_id` отвергает ЯДРО (`lib/spec/spec-item-files.ts`,
-- `findPlan` — понятный текст на форме), а триггер — второй контур для
-- записи в обход кода.
--
-- Живость строки плана здесь НЕ проверяется, и это отличается от
-- `payment_scope`. Оплата — уже случившееся движение денег: документ к
-- отменённой оплате продолжает объяснять историю, поэтому `deleted_at is null`
-- в условии оплаты стоит, а связь всё равно снимается — так решил тикет 06.
-- Строка графика отменяемой не бывает: `removePaymentPlan` её мягко удаляет, и
-- счёт, приложенный к плану, обязан остаться основанием. Поэтому живость строки
-- плана не проверяется вовсе — иначе мягкое удаление плана молча стирало бы
-- привязку счёта в момент, когда строка перестала читаться.
--
-- Применение: `npx supabase db push`. Файл идемпотентен: повторный прогон
-- ничего не ломает.

begin;

-- ---------------------------------------------------------------------------
-- 1. Ссылка на строку графика
-- ---------------------------------------------------------------------------
-- `add column if not exists` — как в 20261010_001 и 20261011_001: в живом
-- проекте таблица уже существует, и файл обязан быть безопасным при повторном
-- прогоне.
alter table public.spec_item_files
  add column if not exists payment_plan_id uuid;

comment on column public.spec_item_files.payment_plan_id is
  'Плановая строка, к которой прикреплён документ (счёт — основание платежа). NULL — обычный файл позиции. Не заменяет payment_id: при отметке «Оплачено» счёт получает вторую связь и остаётся привязан к плану. Проверка принадлежности — триггером spec_item_files_payment_plan_scope.';

-- Внешний ключ: `RESTRICT` (ADR 0004). Проверка по колонке, а не по имени: имя
-- в уже применённой версии могло быть любым (тот же приём, что у payment_id).
do $$
begin
  if not exists (
    select 1
      from pg_constraint c
      join pg_attribute a
        on a.attrelid = c.conrelid
       and a.attnum = any (c.conkey)
     where c.conrelid = 'public.spec_item_files'::regclass
       and c.contype = 'f'
       and a.attname = 'payment_plan_id'
  ) then
    alter table public.spec_item_files
      add constraint spec_item_files_payment_plan_id_fkey
      foreign key (payment_plan_id) references public.spec_item_payment_plans (id)
      on delete restrict;
  end if;
end $$;

-- Документы одной строки графика: список в карточке планового платежа читается
-- именно так. Частичный индекс — строка без `payment_plan_id` (а это
-- большинство файлов позиции) места в индексе не занимает.
create index if not exists spec_item_files_payment_plan_id_idx
  on public.spec_item_files (payment_plan_id)
  where payment_plan_id is not null and deleted_at is null;

-- ---------------------------------------------------------------------------
-- 2. Принадлежность: файл и строка графика — одной позиции, организации и проекта
-- ---------------------------------------------------------------------------
-- Проверка стоит на ОБОИХ событиях, без развилки `tg_op`: ссылка обязана быть
-- верной в любой момент жизни строки, а не только при вставке. Развилка
-- «при UPDATE снимать, при INSERT падать» дала бы два разных ответа на одно и
-- то же расхождение и, главное, не защитила бы от `UPDATE`, который сам
-- приносит чужой `payment_plan_id`.
--
-- Сверяются три величины, а не одна. Позиции мало: `org_id` и `project_id` —
-- денормализация (их подтягивает `payment_plan_sync_scope`), и расхождение по
-- ним означало бы файл в одной организации со ссылкой на план в другой.
create or replace function public.spec_item_files_payment_plan_scope()
returns trigger
language plpgsql
as $function$
declare
  v_item    uuid;
  v_org     uuid;
  v_project uuid;
begin
  if new.payment_plan_id is null then
    return new;
  end if;

  select pl.spec_item_id, pl.org_id, pl.project_id
    into v_item, v_org, v_project
    from public.spec_item_payment_plans pl
   where pl.id = new.payment_plan_id;

  if v_item is null
     or v_item <> new.spec_item_id
     or v_org <> new.org_id
     or v_project <> new.project_id then
    -- Чужая позиция, чужая организация, чужой проект, несуществующая строка —
    -- любое расхождение снимает ссылку, а не ломает строку файла.
    raise notice
      'spec_item_files: payment_plan_id % не принадлежит позиции % организации % — ссылка снята',
      new.payment_plan_id, new.spec_item_id, new.org_id;
    new.payment_plan_id := null;
  end if;

  return new;
end
$function$;

drop trigger if exists spec_item_files_payment_plan_scope
  on public.spec_item_files;
create trigger spec_item_files_payment_plan_scope
  before insert or update on public.spec_item_files
  for each row execute function public.spec_item_files_payment_plan_scope();

commit;
